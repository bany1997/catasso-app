export function formatAOA(amount: number): string {
  return new Intl.NumberFormat('pt-AO', {
    style: 'currency',
    currency: 'AOA',
    maximumFractionDigits: 2,
    minimumFractionDigits: 2,
  })
    .format(amount)
    .replace('AOA', 'Kz');
}
